"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path"),crypto=require("node:crypto");
const root=process.argv[2]||(fs.existsSync(path.join(__dirname,"training-buses-data-work.js"))?__dirname:path.resolve(__dirname,".."));
const suffix=fs.existsSync(path.join(root,"training-buses-data-work.js"))?"-work":"";
const context={window:{}};
vm.createContext(context);
const dataSource=fs.readFileSync(path.join(root,"training-buses-data"+suffix+".js"),"utf8"),prefix="window.KNIGHT_TRAINING_BUS_FIXTURE=";
assert.ok(dataSource.startsWith(prefix)&&dataSource.endsWith(";"));
assert.equal(crypto.createHash("sha256").update(dataSource.slice(prefix.length,-1)).digest("hex"),"ccd9c4145e60fbcee7bb1637bef3a528b38273d5dd9365685a135d564fd4b68f");
vm.runInContext(dataSource,context);
vm.runInContext(fs.readFileSync(path.join(root,"training-buses-core"+suffix+".js"),"utf8"),context);
const model=context.window.KnightTrainingBuses,fixture=context.window.KNIGHT_TRAINING_BUS_FIXTURE;
assert.equal(model.error,null);assert.equal(model.valid,true);
let view=model.snapshot();assert.equal(view.vehicles.length,3);assert.equal(view.time_s,0);
assert.deepEqual(Array.from(view.vehicles,v=>v.vehicle_id),["TRAINING-BUS-001","TRAINING-BUS-002","TRAINING-BUS-003"]);
for(let i=0;i<3;i++)assert.equal(view.vehicles[i].trail_id,fixture.buses[i].trail_id);
model.setElapsed(60);view=model.snapshot();
for(let i=0;i<3;i++){
 const expected=fixture.buses[i].positions[6].position_lonlat,actual=view.vehicles[i].position_lonlat;
 assert.ok(Math.hypot(actual[0]-expected[0],actual[1]-expected[1])<1e-7);
 assert.equal(view.vehicles[i].completed_trail_lonlat.length>=2,true);
}
const route=fixture.buses[0].route,firstLength=Math.hypot(route.geometry_m[1][0]-route.geometry_m[0][0],route.geometry_m[1][1]-route.geometry_m[0][1]);
const totalLength=firstLength+Math.hypot(route.geometry_m[2][0]-route.geometry_m[1][0],route.geometry_m[2][1]-route.geometry_m[1][1]);
model.setElapsed(firstLength/totalLength*120);
const corner=model.snapshot().vehicles[0];
assert.ok(Math.hypot(corner.position_lonlat[0]-route.geometry_lonlat[1][0],corner.position_lonlat[1]-route.geometry_lonlat[1][1])<1e-9);
const outgoing=(Math.atan2(route.geometry_m[2][0]-route.geometry_m[1][0],route.geometry_m[2][1]-route.geometry_m[1][1])*180/Math.PI+360)%360;
assert.ok(Math.abs(corner.heading_deg-outgoing)<1e-6);
model.setElapsed(60);
model.select("TRAINING-BUS-003");assert.equal(model.elapsed,60);assert.equal(model.selectedBusId,"TRAINING-BUS-003");
model.advance(10);assert.equal(model.elapsed,60);assert.equal(model.snapshot().vehicles[2].simulated_speed_kmh,0);
model.toggle();model.advance(1);assert.equal(model.elapsed,61);assert.ok(model.snapshot().vehicles[2].simulated_speed_kmh>0);
model.setElapsed(120);assert.equal(model.paused,true);assert.ok(model.snapshot().vehicles.every(v=>v.simulated_speed_kmh===0));
const bad=JSON.parse(JSON.stringify(fixture));bad.buses[0].positions[3].elapsed_s=99;
context.window.KNIGHT_TRAINING_BUS_FIXTURE=bad;
vm.runInContext(fs.readFileSync(path.join(root,"training-buses-core"+suffix+".js"),"utf8"),context);
assert.equal(context.window.KnightTrainingBuses.valid,false);
console.log("three-bus training model: passed");
